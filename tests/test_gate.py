def message(line: str) -> str:
    return f"Fix the Hungarian style's default\n\nWhy it changed.\n\n{line}\nRefs #2\n"


def new_repo(path: Path) -> Callable[..., str]:
    """A git repo at path, and a function that runs git in it with an invented author and no hooks."""
    no_hooks = path / ".no-hooks"
    no_hooks.mkdir()

    def run(*args: str) -> str:
        identity = ["-c", "user.name=Test", "-c", "user.email=test@example.org", "-c", "commit.gpgsign=false"]
        done = gate.git(*identity, "-c", f"core.hooksPath={no_hooks}", *args, cwd=path)
        assert done.returncode == 0, done.stderr
        return done.stdout.strip()

    run("init", "-q", "-b", "main")
    return run


def commit_file(run: Callable[..., str], path: Path, name: str, subject: str) -> None:
    (path / name).write_text(f"{name}\n", encoding="utf-8")
    run("add", "-A")
    run("commit", "-q", "-m", subject)


